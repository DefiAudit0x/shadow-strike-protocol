"""
shadow_strike.reporting.report_generator
===========================================
The "ربط بـ DeFiAudit" piece from the roadmap: turns a verified
VerificationResult (or a stored proof_artifact dict, e.g. read back
from the Knowledge Store) into a Markdown audit finding — the exact
unit DeFiAudit-style reports are assembled from.

Zero extra dependencies; pure string templating. If you want this as
a polished PDF/Word deliverable instead of Markdown, pipe the output
through this project's docx/pdf tooling — this module's job stops at
producing the authoritative Markdown finding, not at page layout.
"""

from __future__ import annotations

from datetime import datetime, timezone

SEVERITY_BY_CLASS = {
    "reentrancy": "Critical",
    "oracle_manipulation": "Critical",
    "flash_loan": "Critical",
    "price_manipulation": "Critical",
    "access_control": "High",
    "signature_replay": "High",
    "initialization": "High",
    "upgradeability": "High",
    "accounting": "Medium",
    "cross_contract": "Medium",
    "economic": "Medium",
}


def generate_finding_markdown(proof_artifact: dict, finding_id: str = "SS-001") -> str:
    """proof_artifact: the dict produced by Verifier.verify(...).proof_artifact
    (same shape whether it came straight off a run or was read back out
    of KnowledgeStore.save_proof / library_entries)."""
    scenario = proof_artifact["scenario"]
    vuln_class = scenario["vulnerability_class"]
    severity = SEVERITY_BY_CLASS.get(vuln_class, "Medium")
    engine = proof_artifact.get("engine", "unknown")
    engine_note = (
        "⚠️ **mock engine** — this proof was produced by the offline simulator, "
        "NOT a real EVM. Re-verify with `--engine foundry` against a real fork "
        "before this finding is reported to a client."
        if engine == "mock" else
        f"✅ verified via `{engine}` against a real forked EVM state."
    )

    condition_lines = "\n".join(
        f"- {'✅' if c['passed'] else '❌'} `{c['expression']}` — {c['description']}"
        for c in proof_artifact.get("condition_results", [])
    )
    invariant_lines = (
        "\n".join(f"- ⚠️ `{inv}`" for inv in proof_artifact.get("invariant_violations", []))
        or "_none violated_"
    )
    steps_lines = "\n".join(
        f"{i+1}. `{s['caller']}` calls `{scenario['target_protocol']}.{s['target']}.{s['function']}`"
        + (f" (value: {s['value_eth']} ETH)" if s.get("value_eth") else "")
        + (f" — {s['comment']}" if s.get("comment") else "")
        for i, s in enumerate(scenario["steps"])
    )

    return f"""## Finding {finding_id}: {scenario['hypothesis'][:80]}

| | |
|---|---|
| **Severity** | {severity} |
| **Category** | {vuln_class.replace('_', ' ').title()} |
| **Target** | {scenario['target_protocol']} |
| **Scenario ID** | `{scenario['scenario_id']}` |
| **Status** | {'**VERIFIED — attack confirmed executable**' if proof_artifact.get('condition_results') and all(c['passed'] for c in proof_artifact['condition_results']) and not proof_artifact.get('reverted') else 'NOT VERIFIED'} |
| **Generated** | {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')} |

### Hypothesis

{scenario['hypothesis']}

### Proof of Exploitability

{engine_note}

**Attack sequence:**

{steps_lines}

**Success conditions evaluated against actual post-execution state:**

{condition_lines}

**Invariants checked (informational; do not affect the verdict):**

{invariant_lines}

### Assumptions

{chr(10).join(f'- {a}' for a in scenario.get('assumptions', [])) or '_none stated_'}

### Recommendation

{_recommendation_for(vuln_class)}

---
*Generated by Shadow Strike Protocol. This finding was produced by executing
an actual transaction sequence against {'a simulated' if engine == 'mock' else 'a forked'}
EVM state and evaluating success conditions against the resulting state —
it is not a static-analysis guess.*
"""


def _recommendation_for(vuln_class: str) -> str:
    return {
        "reentrancy": "Apply checks-effects-interactions ordering (update state before external calls), "
                      "or add a reentrancy guard (OpenZeppelin `ReentrancyGuard`) to the affected function(s).",
        "access_control": "Add an explicit authorization check (`onlyOwner`/role-based) to the affected "
                           "function, and audit every other function in the contract for the same gap.",
        "oracle_manipulation": "Replace the spot-price read with a manipulation-resistant source: a "
                                "time-weighted average price (TWAP) over a meaningful window, or a "
                                "decentralized oracle (Chainlink) with staleness/deviation checks.",
        "price_manipulation": "Adopt ERC-4626's virtual shares/offset mitigation, or seed the vault with "
                               "a protocol-owned minimum deposit at deployment to defeat the first-depositor attack.",
        "signature_replay": "Bind signatures to a nonce (tracked and invalidated on use), the deploying "
                             "chain's `block.chainid`, and the specific `address(this)` via EIP-712 domain separation.",
        "initialization": "Add the `initializer` modifier to every `initialize()` in the inheritance chain, "
                           "and call `_disableInitializers()` in the implementation contract's constructor.",
    }.get(vuln_class, "Engage the Shadow Strike team to scope a bespoke remediation for this finding class.")


def generate_summary_report(proof_artifacts: list[dict], target_protocol: str) -> str:
    """Roll up multiple findings (e.g. all verified proofs for one
    engagement, pulled from KnowledgeStore) into one report shell."""
    findings_md = "\n\n".join(
        generate_finding_markdown(p, finding_id=f"SS-{i+1:03d}")
        for i, p in enumerate(proof_artifacts)
    )
    counts: dict[str, int] = {}
    for p in proof_artifacts:
        sev = SEVERITY_BY_CLASS.get(p["scenario"]["vulnerability_class"], "Medium")
        counts[sev] = counts.get(sev, 0) + 1
    summary_line = ", ".join(f"{n} {sev}" for sev, n in sorted(counts.items(), key=lambda kv: kv[0]))

    return f"""# Shadow Strike Security Assessment — {target_protocol}

**Date:** {datetime.now(timezone.utc).strftime('%Y-%m-%d')}
**Findings:** {len(proof_artifacts)} ({summary_line or 'none'})

Every finding below was produced by executing a concrete transaction
sequence and evaluating success conditions against actual post-execution
state — not inferred from static source review alone.

{findings_md}
"""
